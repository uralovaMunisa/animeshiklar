export function searchLocalAnimePictures({ query = '', page = 1, perPage = 30 } = {}) {
  const trimmed = query.trim().toLowerCase();
  let results = [...ANIME_PICTURES_DATA];

  if (trimmed) {
    results = results.filter((pic) => {
      return (
        pic.title.toLowerCase().includes(trimmed) ||
        pic.category.toLowerCase().includes(trimmed) ||
        pic.author.toLowerCase().includes(trimmed) ||
        (pic.tags && pic.tags.some((t) => t.toLowerCase().includes(trimmed)))
      );
    });
  }

  const start = (page - 1) * perPage;
  const paged = results.slice(start, start + perPage);

  return {
    items: paged,
    total: results.length,
    hasMore: start + perPage < results.length
  };
}
